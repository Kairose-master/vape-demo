"""Authenticated native registration channel and strictly metadata-only preflight.

The capability is generated by the launcher, delivered only in the private app
bundle, never in a URL/public response. Same OS user remains in the trust boundary.
No selected-file plaintext, model output, paths, or credentials are accepted.
"""
import hmac
import http.server
import json
import threading
import uuid
from vape.providers.model_routing import ModelPolicy, VerifiedResource, ServerContext
from vape.providers.local_provider import LocalConfig
from vape.providers.openai_cloud import CloudConfig

POLICY_VERSION=1
CONTEXT=ServerContext('native-selected-user','analyst','selected-read')
RULES=[dict(id='read-'+level,role=CONTEXT.role,workflow=CONTEXT.workflow,classification=level,
            operation='read',destination=None,model=None,effect='allow') for level in ('L1','L2','L3')]
RULES += [dict(id='cloud-'+level,role=CONTEXT.role,workflow=CONTEXT.workflow,classification=level,
            operation='model_send',destination='cloud-model',model='approved-cloud',effect='allow') for level in ('L2','L3')]
POLICY=ModelPolicy(dict(version=POLICY_VERSION,default='deny',rules=RULES))

class Coordinator:
    def __init__(self):self.records={};self.lock=threading.RLock()
    def register(self,value):
        with self.lock:
            if not isinstance(value,dict) or set(value)!={'resource_id','level','classification_revision','policy_version','active'}:raise ValueError()
            uuid.UUID(value['resource_id'])
            if type(value['level']) is not int or value['level'] not in (1,2,3) or type(value['classification_revision']) is not int or value['classification_revision']<1 or type(value['policy_version']) is not int or value['policy_version']!=POLICY_VERSION or type(value['active']) is not bool:raise ValueError()
            old=self.records.get(value['resource_id'])
            if old:
                if not old['active'] or value['classification_revision']<old['classification_revision']:raise ValueError()
                if value['classification_revision']==old['classification_revision'] and value['level']!=old['level']:raise ValueError()
                if value['classification_revision']>old['classification_revision']+1:raise ValueError()
            elif value['classification_revision']!=1:raise ValueError()
            self.records[value['resource_id']]=dict(value)
            return {'status':'registered','resource_id':value['resource_id'],'classification_revision':value['classification_revision'],'policy_version':POLICY_VERSION}
    def preflight(self,value):
        with self.lock:
            result={'decision':'deny','policyDecision':'deny','reason':'invalid_request','bodyRead':False,'deliveryStatus':'not_sent','grantedEffects':[], 'retryAutomatically':False,'policy_version':POLICY_VERSION,'inferencePerformed':False}
            if not isinstance(value,dict) or set(value)!={'resource_id','classification_revision','policy_version','route','action'}:return result
            if not isinstance(value['resource_id'],str) or type(value['classification_revision']) is not int or type(value['policy_version']) is not int:return result
            r=self.records.get(value['resource_id'])
            if not r or not r['active']:result['reason']='unregistered_or_inactive';return result
            if value['classification_revision']!=r['classification_revision'] or type(value['policy_version']) is not int or value['policy_version']!=POLICY_VERSION:result['reason']='stale_classification_or_policy';return result
            result.update(classification_revision=r['classification_revision'],level=r['level'])
            if value['action']!='model_send':result['reason']='separate_effect_approval_required';return result
            if value['route'] not in ('local','cloud'):result['reason']='unknown_route';return result
            if value['route']=='cloud':
                metadata=VerifiedResource(r['resource_id'],'L'+str(r['level']),'')
                evaluated=POLICY.evaluate(metadata,CONTEXT,'model_send','cloud-model','approved-cloud')
                if evaluated['decision']!='allow':result['reason']=evaluated['reason'];return result
                blocked=CloudConfig().blocked_reason()
            else:
                # Fixed local route, all registered levels; no URL/model/subject from callers.
                blocked=LocalConfig().blocked_reason()
            result.update(policyDecision='allow',reason=blocked)
            # No capability or reusable approval is issued while providers are unavailable.
            return result

def make_server(token,coordinator=None):
    if not isinstance(token,str) or len(token)<32:raise ValueError('Private launcher capability required')
    coordinator=coordinator or Coordinator()
    class Handler(http.server.BaseHTTPRequestHandler):
        def log_message(self,*args):pass
        def do_POST(self):
            if self.headers.get('Host')!='127.0.0.1:'+str(self.server.server_port) or self.headers.get('Origin'):
                self.send_error(403);return
            if not hmac.compare_digest(self.headers.get('Authorization',''),'Bearer '+token):self.send_error(403);return
            try:
                length=int(self.headers.get('Content-Length','0'))
                if not 0<length<=2048:raise ValueError()
                value=json.loads(self.rfile.read(length))
                if self.path=='/native/register':out=coordinator.register(value)
                elif self.path=='/native/preflight':out=coordinator.preflight(value)
                else:self.send_error(404);return
            except (ValueError,TypeError,KeyError):self.send_error(400);return
            data=json.dumps(out).encode();self.send_response(200);self.send_header('Content-Type','application/json');self.send_header('Cache-Control','no-store');self.send_header('Content-Length',str(len(data)));self.end_headers();self.wfile.write(data)
        def do_GET(self):self.send_error(405)
    return http.server.ThreadingHTTPServer(('127.0.0.1',0),Handler)
